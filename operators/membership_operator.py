#Membership operators
'''
-These are used to check if an object is a member of an iterable.
-These are keywords which return boolean True or False.
'''
#Working of (in):
'''
-present = true
-not present = False
'''

#Working of (not in):
'''
-not present = True
-present = False
'''
print('t' not in 'python')
print(2 in [1,2,3,4])

