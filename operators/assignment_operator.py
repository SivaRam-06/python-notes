#Assignment operators
'''
These are special symbols used for assigning or updating values present in
variables.
'''
'''
-operand     operation
    =        assignment
    +=       adding and re-assignment
    -=       subtracting and re-assignment to the same variable
    *=       multiply and assignment
    /=       divide and assignment
    etc...
'''
a = 30  
a -= 5    #a = a-5
a += 15
a *= 2
print(a)
